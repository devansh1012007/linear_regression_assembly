#!/usr/bin/env python3
"""Generate the DoD-3 evidence plots from COMMITTED raw results.

Outputs (results/plots/, dpi=110, regenerated by `make plots` / `make repro`):
  roofline.png        bandwidth ceilings + FMA peak + measured kernels,
                      p* crossover marked (machine.json + gram-bench-v4.json)
  thread-scaling.png  ols_gram_mt 1t vs mt2 vs the measured bandwidth
                      ceilings (gram-bench-v4.json + machine.json)
  ladder.png          baseline ladder, 4 cases x 5 rungs (ladder.json)

Every number is read from results/*.json; nothing is hand-typed (README
rule). Run from repo root: python3 tools/make_plots.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
PLOTS = RESULTS / "plots"


def load(name):
    p = RESULTS / name
    if not p.exists():
        sys.exit(f"make_plots: missing {p} (run the corresponding bench first)")
    return json.loads(p.read_text())


def setup_mpl():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.font_manager as fm
    for f in ("/usr/share/fonts/truetype/chinese/NotoSansSC-Regular.ttf",
              "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"):
        if Path(f).exists():
            fm.fontManager.addfont(f)
    import matplotlib.pyplot as plt
    plt.rcParams["font.sans-serif"] = ["Noto Sans SC", "DejaVu Sans"]
    plt.rcParams["axes.unicode_minus"] = False
    return plt


def roofline(plt, mach, gb4):
    """Classic roofline: attainable GFLOP/s vs arithmetic intensity (FLOP/byte).

    Fused Gram pass per row: q*(q+1) FLOP (each FMA = 2 FLOP counted),
    (q+1)*8 bytes read for the Z row (G written once per matrix: amortized).
    => AI = q/8 FLOP/byte; p* formula in machine.json matches: p*+1 = 8*peak/bw.
    """
    fma = mach["fma_peak_gflops"]
    bw = mach["bandwidth_ladder"]
    dram1t = bw["DRAM"]["gbps_1t"]
    dram_all = bw["DRAM"]["gbps_allt"]
    l2 = bw["L2"]["gbps_1t"]

    fig, ax = plt.subplots(figsize=(8.6, 5.2), constrained_layout=True)
    ai = [i / 100 for i in range(1, 1200)]  # 0.01 .. 12 FLOP/byte
    for ceiling, gbps, label, style in (
        (dram1t, dram1t, f"DRAM 1-thread ({dram1t:.1f} GB/s)", "-"),
        (dram_all, dram_all, f"DRAM all-thread ({dram_all:.1f} GB/s)", "--"),
        (l2, l2, f"L2 1-thread ({l2:.1f} GB/s)", ":"),
    ):
        ax.plot(ai, [min(gbps * x, fma) for x in ai], style, lw=1.1,
                color="gray", alpha=0.8, label=label)
    ax.axhline(fma, color="tab:red", lw=1.4,
               label=f"FMA peak 1-thread ({fma:.1f} GFLOP/s)")

    # measured kernels: one point per gram-bench-v4 case
    for name, c in gb4["cases"].items():
        if name.endswith("_mt2") or "_DRAM" not in name and "_L2" not in name:
            continue
        q = int(name.split("_")[0][1:])
        n = int(name.split("_")[1][1:])
        d = c["derived"]
        gflops = q * (q + 1) * n / d["median_s"] / 1e9
        mem = "L2" if name.endswith("_L2") else "DRAM"
        ax.plot(q / 8, gflops, "o", ms=7,
                color="tab:blue" if mem == "DRAM" else "tab:green")
        ax.annotate(f"q={q}", (q / 8, gflops), textcoords="offset points",
                    xytext=(6, 4), fontsize=8)
    ax.plot([], [], "o", color="tab:blue", label="measured, DRAM-resident")
    ax.plot([], [], "o", color="tab:green", label="measured, L2-resident")

    # p* crossover for the 1-thread DRAM line (machine.json roofline)
    ai_star = fma / dram1t
    ax.axvline(ai_star, color="tab:purple", lw=0.9, ls="-.", alpha=0.7)
    ax.annotate(f"p* = {mach['roofline']['p_star_1t_dram']} (q+1 = 8·AI*, 1t DRAM)",
                (ai_star, fma * 0.06), rotation=90, fontsize=8,
                color="tab:purple", ha="right", va="bottom")

    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("arithmetic intensity (FLOP / byte)  =  q/8 for the fused Gram pass")
    ax.set_ylabel("attainable GFLOP/s")
    ax.set_title("Roofline, measured ceilings and kernels (results/machine.json + gram-bench-v4.json)")
    ax.grid(alpha=0.3, which="both")
    ax.legend(fontsize=8, loc="upper left")
    PLOTS.mkdir(parents=True, exist_ok=True)
    fig.savefig(PLOTS / "roofline.png", dpi=110)
    plt.close(fig)


def thread_scaling(plt, mach, gb4):
    """ols_gram_mt 1t vs mt2 against the measured bandwidth ceilings."""
    dram1t = mach["bandwidth_ladder"]["DRAM"]["gbps_1t"]
    dram_all = mach["bandwidth_ladder"]["DRAM"]["gbps_allt"]

    labels, one_t, mt2 = [], [], []
    for q in (8, 17):
        c1 = gb4["cases"][f"q{q}_n200000_DRAM"]["derived"]
        c2 = gb4["cases"][f"q{q}_n200000_DRAM_mt2"]["derived"]
        labels.append(f"q={q}, n=2e5 (DRAM)")
        one_t.append(c1["gbps"])
        mt2.append(c2["gbps"])

    fig, ax = plt.subplots(figsize=(7.6, 4.6), constrained_layout=True)
    x = range(len(labels))
    w = 0.34
    ax.bar([i - w / 2 for i in x], one_t, w, label="ols_gram 1 thread", color="tab:blue")
    ax.bar([i + w / 2 for i in x], mt2, w, label="ols_gram_mt T=2", color="tab:orange")
    for i, (a, b) in enumerate(zip(one_t, mt2)):
        ax.text(i - w / 2, a, f"{a:.2f}", ha="center", va="bottom", fontsize=8)
        ax.text(i + w / 2, b, f"{b:.2f}", ha="center", va="bottom", fontsize=8)
        ax.text(i + w / 2, b + 2.2, f"{b / dram_all * 100:.1f}% of all-thread",
                ha="center", va="bottom", fontsize=7.5, color="dimgray")
    ax.axhline(dram1t, color="gray", ls=":", lw=1.2,
               label=f"DRAM 1-thread ceiling ({dram1t:.1f} GB/s)")
    ax.axhline(dram_all, color="tab:red", ls="--", lw=1.2,
               label=f"DRAM all-thread ceiling ({dram_all:.1f} GB/s)")
    ax.set_xticks(list(x))
    ax.set_xticklabels(labels)
    ax.set_ylabel("GB/s")
    ax.set_ylim(0, dram_all * 1.18)
    ax.set_title("Thread scaling vs measured bandwidth (H5: RED on this 2-vCPU quota host)")
    ax.legend(fontsize=8, loc="upper left")
    ax.grid(alpha=0.3, axis="y")
    fig.savefig(PLOTS / "thread-scaling.png", dpi=110)
    plt.close(fig)


def ladder(plt, lad):
    """Baseline ladder: ns/row for the 4 cases x 5 rungs, log scale."""
    rung_order = ["naive-O2", "naive-O3", "intrin", "intrin-O3", "asm-v3", "numpy-blas"]
    rungs = [r for r in rung_order
             if any(rr["rung"] == r for rr in lad["runs"])]
    cases = lad["cases"]
    case_names = [f"n={n:.0e}\nq={q}" for n, q in
                  [(c[0], c[1]) for c in cases]]
    # ^ {n:.0e} on ints gives 2e+05; prettify:
    case_names = []
    for n, q in cases:
        nn = f"{n:.0e}".replace("e+0", "e").replace("e+", "e")
        case_names.append(f"n={nn}  q={q}")

    fig, ax = plt.subplots(figsize=(9.2, 4.8), constrained_layout=True)
    colors = {"naive-O2": "tab:gray", "naive-O3": "silver", "intrin": "tab:green",
              "intrin-O3": "darkseagreen", "asm-v3": "tab:blue",
              "numpy-blas": "tab:red"}
    x = range(len(cases))
    nw = len(rungs)
    w = 0.8 / nw
    for j, rung in enumerate(rungs):
        vals = []
        for n, q in cases:
            match = [r["ns_row"] for r in lad["runs"]
                     if r["rung"] == rung and r["n"] == n and r["q"] == q]
            vals.append(match[0] if match else None)
        xs = [i - 0.4 + w / 2 + j * w for i in range(len(cases))]
        ax.bar(xs, [v if v else 0 for v in vals], w, label=rung,
               color=colors.get(rung, None))
        for xi, v in zip(xs, vals):
            if v:
                ax.text(xi, v * 1.04, f"{v:.1f}", ha="center", va="bottom",
                        fontsize=7, rotation=90)
    # mark the one case asm wins
    ax.annotate("asm-v3 wins\n(+11% vs numpy)", (3.08, 21.5), fontsize=8,
                color="tab:blue", ha="left")
    ax.set_yscale("log")
    ax.set_ylim(5, 200)
    ax.set_xticks(list(x))
    ax.set_xticklabels(case_names)
    ax.set_ylabel("ns / row (log scale, lower is better)")
    ax.set_title("Baseline ladder (results/ladder.json): same workload, best-of-3, "
                 "sandbox CPU-quota host")
    ax.legend(fontsize=8, ncol=len(rungs), loc="upper left",
              bbox_to_anchor=(0, 1.02))
    ax.grid(alpha=0.3, axis="y", which="both")
    fig.savefig(PLOTS / "ladder.png", dpi=110)
    plt.close(fig)


def main():
    mach = load("machine.json")
    gb4 = load("gram-bench-v4.json")
    lad = load("ladder.json")
    plt = setup_mpl()
    roofline(plt, mach, gb4)
    thread_scaling(plt, mach, gb4)
    ladder(plt, lad)
    for f in ("roofline.png", "thread-scaling.png", "ladder.png"):
        p = PLOTS / f
        print(f"wrote {p} ({p.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
