#!/usr/bin/env python3
"""Append measured machine results to docs/perf-log.md from results/machine.json.
No measured number is ever typed by hand (AGENTS.md rule 1)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
m = json.loads((ROOT / "results" / "machine.json").read_text())
lad = m["bandwidth_ladder"]
lines = []
lines.append("\n## Measurements (generated by tools/update_perflog.py; DO NOT hand-edit)\n")
lines.append(f"### {m['date'][:10]} machine/fma-peak | measured | - | predicted: knee 8-10, 2 FMA/cy | "
             f"measured: knee {m['fma_best_nacc']}, peak {m['fma_peak_gflops']} GFLOP/s | "
             f"VERDICT: 2 FMA/cy confirmed ({m['fma_peak_gflops']}/16={m['fma_peak_gflops']/16:.3f} GHz vs depadd "
             f"{m['clock']['depadd_gops_s']} GHz, {abs(m['fma_peak_gflops']/16/m['clock']['depadd_gops_s']-1)*100:.1f}% gap) | "
             "evidence: results/machine.json\n")
lines.append(f"### {m['date'][:10]} machine/bandwidth | measured | - | predicted: L1>100, L2 50-80, L3 30-60, DRAM 8-15 GB/s 1t | "
             f"measured: L1 {lad['L1']['gbps_1t']}, L2 {lad['L2']['gbps_1t']}, L3 {lad['L3']['gbps_1t']}, "
             f"DRAM {lad['DRAM']['gbps_1t']} 1t / {lad['DRAM']['gbps_allt']} all-t GB/s | "
             "VERDICT: L1/L2 above prediction; L3/DRAM below (shared cloud caches, vCPU quota); single thread = "
             f"{lad['DRAM']['gbps_1t']/lad['DRAM']['gbps_allt']*100:.0f}% of all-thread DRAM | "
             "evidence: results/machine.json\n")
lines.append(f"### {m['date'][:10]} machine/roofline | measured | - | - | "
             f"measured p* = {m['roofline']['p_star_1t_dram']} (1 thread, DRAM) | "
             "VERDICT: fused Gram is DRAM-bound for p+1 < ~28, FMA-bound above; Phase-2 narrow kernels are "
             "bandwidth-bound and accuracy flops are free there | evidence: results/machine.json\n")
out = ROOT / "docs" / "perf-log.md"
out.write_text(out.read_text().split("\n## Measurements")[0] + "\n".join(lines) + "\n")
print("perf-log regenerated")
