#!/usr/bin/env python3
"""Generate exact-hex constants for src/core/special.asm.

Analysis recorded with each block (why this degree / this form):
- exp: e^r, r in [-ln2/2, ln2/2]; Taylor to r^13/13! -> truncation
  r^14/14! ~ 4e-18 (<< half-ulp 1.1e-16 of the result in [0.7,1.42]).
- log: ln(m) = 2s*P(s^2), s = (m-1)/(m+1) in [-0.1716, 0.1716];
  P(u) = sum u^j/(2j+1), j = 0..10 -> truncation ~1.6e-17 abs.
- lgamma: Lanczos g=7 n=9 (Wikipedia/GSL set); reflection for x < 0.5
  needs sin(pi*x) for pi*x in (0, pi/2): Taylor to w^21/21! -> ~2.6e-16.
- ibeta: NR betacf constants (FPMIN, eps, maxit).
"""
import struct


def h(x):
    return f"0x{struct.unpack('<Q', struct.pack('<d', x))[0]:016X}", x


print("; ---- generated by tools/gen_special_consts.py (do not hand-edit) ----")

print("\n; exp: Taylor 1/k!, k = 1..13 (trunc r^14/14! ~ 4e-18)")
for k in range(13, 0, -1):
    bits, v = h(1.0 / __import__("math").factorial(k))
    print(f"exp_c{k:<2d}: dq {bits}   ; 1/{k}! = {v!r}")

print("\n; log: 1/(2j+1), j = 10..0 (P(u) Horner, u = s^2)")
for j in range(10, -1, -1):
    bits, v = h(1.0 / (2 * j + 1))
    print(f"log_p{j:<2d}: dq {bits}   ; 1/{2*j+1} = {v!r}")

print("\n; lgamma: Lanczos g=7 n=9 (c0..c8), g, 0.5*ln(2pi), ln(pi)")
lg = [0.99999999999980993, 676.5203681218851, -1259.1392167224028,
      771.32342877765313, -176.61502916214059, 12.507343278686905,
      -0.13857109526572012, 9.9843695780195716e-6, 1.5056327351493116e-7]
for i, c in enumerate(lg):
    bits, v = h(c)
    print(f"lg_c{i}: dq {bits}   ; {v!r}")
for name, v in [("lg_g", 7.0), ("lg_half_ln2pi", 0.5 * (2 * 3.141592653589793) ** 0.5 and 0.9189385332046727),
                ("lg_ln_pi", 1.1447298858494002)]:
    bits, vv = h(v)
    print(f"{name}: dq {bits}   ; {vv!r}")

print("\n; sin Taylor (pi*x in (0, pi/2)): (-1)^j/(2j+1)!, j = 5..0")
import math as m
for j in range(5, -1, -1):
    bits, v = h(((-1) ** j) / m.factorial(2 * j + 1))
    print(f"sin_c{j}: dq {bits}   ; (-1)^{j}/{2*j+1}! = {v!r}")

print("\n; misc")
for name, v in [("pi_hi", 3.141592653589793116e-016 * 1e16),
                ("pi_lo", 1.2246467991473532072e-16)]:
    pass
# pi split: pi = 3.141592653589793122... double = 0x400921FB54442D18
bits, v = h(3.141592653589793)
print(f"pi_d:   dq {bits}   ; {v!r}")
for name, v in [("ib_fpm", 2.2250738585072014e-308), ("ib_eps", 1e-15),
                ("ib_half", 0.5), ("ib_two", 2.0)]:
    bits, vv = h(v)
    print(f"{name}: dq {bits}   ; {vv!r}")
